// Command generate derives SDK selection and dispatch from the reviewed CLI catalog.
package main

import (
	"bytes"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"

	contract "github.com/Conv-AI/convai-cli/api"
	"github.com/Conv-AI/convai-cli/internal/jsonwire"
	"gopkg.in/yaml.v3"
)

func main() {
	configOnly := flag.Bool("config", false, "generate SDK selection before running oapi-codegen")
	flag.Parse()
	_, commands, err := contract.Load()
	if err != nil {
		fail(err)
	}
	if *configOnly {
		ids := make([]string, 0, len(commands))
		for _, command := range commands {
			ids = append(ids, command.OperationID)
		}
		config := map[string]any{
			"package": "characterapi", "output": "internal/characterapi/client.gen.go",
			"generate":       map[string]bool{"models": true, "client": true},
			"output-options": map[string]any{"response-type-suffix": "Resp", "include-operation-ids": ids},
		}
		data, err := yaml.Marshal(config)
		if err != nil {
			fail(err)
		}
		if err := os.WriteFile("api/oapi-codegen.yaml", data, 0644); err != nil {
			fail(err)
		}
		var document map[string]any
		if err := jsonwire.Decode(contract.Document, &document); err != nil {
			fail(err)
		}
		// Legacy camelCase/snake_case aliases remain distinct wire fields. Only
		// annotate colliding Go identifiers; never change the owner contract.
		var annotate func(any)
		annotate = func(value any) {
			switch value := value.(type) {
			case map[string]any:
				// Render timestamps verbatim. Legacy REST responses can omit an
				// offset; the CLI must not invent a timezone or reject the page.
				if value["format"] == "date-time" {
					value["x-go-type"] = "string"
				}
				if properties, ok := value["properties"].(map[string]any); ok {
					names := map[string]int{}
					for name := range properties {
						names[goName(name)]++
					}
					for name, schema := range properties {
						if names[goName(name)] > 1 {
							schema.(map[string]any)["x-go-name"] = goName(name) + "Wire" + hex.EncodeToString([]byte(name))
						}
					}
				}
				for _, child := range value {
					annotate(child)
				}
			case []any:
				for _, child := range value {
					annotate(child)
				}
			}
		}
		annotate(document)
		data, err = json.MarshalIndent(document, "", "  ")
		if err != nil {
			fail(err)
		}
		if err := os.MkdirAll(".tools", 0755); err != nil {
			fail(err)
		}
		if err := os.WriteFile(".tools/character.codegen.json", append(data, '\n'), 0644); err != nil {
			fail(err)
		}
		return
	}
	file, err := parser.ParseFile(token.NewFileSet(), "internal/characterapi/client.gen.go", nil, 0)
	if err != nil {
		fail(err)
	}
	methods := map[string]*ast.FuncType{}
	ast.Inspect(file, func(node ast.Node) bool {
		spec, ok := node.(*ast.TypeSpec)
		if !ok || spec.Name.Name != "ClientInterface" {
			return true
		}
		for _, method := range spec.Type.(*ast.InterfaceType).Methods.List {
			methods[method.Names[0].Name] = method.Type.(*ast.FuncType)
		}
		return false
	})
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./tools/generate. DO NOT EDIT.\npackage api\n\nimport (\"bytes\"; \"context\"; \"fmt\"; \"net/http\"; \"github.com/Conv-AI/convai-cli/internal/characterapi\")\n")
	out.WriteString("func (c *Client) dispatch(ctx context.Context, operation string, query map[string]any, body []byte) (*http.Response, error) {\nswitch operation {\n")
	for _, command := range commands {
		name := goName(command.OperationID)
		method, ok := methods[name+"WithBody"]
		if ok {
			name += "WithBody"
		} else {
			method, ok = methods[name]
		}
		if !ok {
			fail(fmt.Errorf("generated SDK lacks operation %s (%s)", command.OperationID, name))
		}
		fmt.Fprintf(&out, "case %q:\n", command.OperationID)
		args := []string{"ctx"}
		for _, param := range method.Params.List[1:] {
			switch param.Names[0].Name {
			case "params":
				typeName := param.Type.(*ast.StarExpr).X.(*ast.Ident).Name
				fmt.Fprintf(&out, "var params characterapi.%s\nif err := decodeQuery(query, &params); err != nil {return nil, err}\n", typeName)
				args = append(args, "&params")
			case "contentType":
				args = append(args, "\"application/json\"")
			case "body":
				args = append(args, "bytes.NewReader(body)")
			case "reqEditors":
			default:
				fail(fmt.Errorf("unsupported generated parameter %s", param.Names[0].Name))
			}
		}
		fmt.Fprintf(&out, "return c.generated.%s(%s)\n", name, strings.Join(args, ", "))
	}
	out.WriteString("default: return nil, fmt.Errorf(\"unapproved CLI operation %q\", operation)\n}\n}\n")
	data, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("internal/api/dispatch.gen.go", data, 0644); err != nil {
		fail(err)
	}
}

func goName(value string) string {
	var parts []string
	for _, part := range strings.FieldsFunc(value, func(r rune) bool { return r == '_' || r == '-' }) {
		parts = append(parts, strings.ToUpper(part[:1])+part[1:])
	}
	return strings.Join(parts, "")
}

func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
