// license-notices collects redistribution notices for every configured binary.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	check := flag.Bool("check", false, "compare rather than replace THIRD_PARTY_NOTICES.txt")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	data, err := os.ReadFile(".goreleaser.yaml")
	if err != nil {
		return err
	}
	var config struct {
		Builds []struct {
			Main   string
			Goos   []string
			Goarch []string
			Ignore []struct{ Goos, Goarch string }
		}
	}
	if err := yaml.Unmarshal(data, &config); err != nil {
		return err
	}
	temp, err := os.MkdirTemp("", "convai-license-notices-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(temp)
	notices := map[string]string{}
	tool := filepath.Join(".tools", "go-licenses")
	if runtime.GOOS == "windows" {
		tool += ".exe"
	}
	for _, build := range config.Builds {
		for _, goos := range build.Goos {
			for _, goarch := range build.Goarch {
				if slices.ContainsFunc(build.Ignore, func(ignore struct{ Goos, Goarch string }) bool {
					return ignore.Goos == goos && ignore.Goarch == goarch
				}) {
					continue
				}
				dir := filepath.Join(temp, goos+"-"+goarch)
				cmd := exec.Command(tool, "save", build.Main, "--ignore", "github.com/Conv-AI/convai-cli", "--save_path", dir)
				cmd.Env = slices.DeleteFunc(os.Environ(), func(value string) bool {
					return strings.HasPrefix(value, "GOOS=") || strings.HasPrefix(value, "GOARCH=") || strings.HasPrefix(value, "CGO_ENABLED=")
				})
				cmd.Env = append(cmd.Env, "GOOS="+goos, "GOARCH="+goarch, "CGO_ENABLED=0")
				if output, err := cmd.CombinedOutput(); err != nil {
					return fmt.Errorf("license collection for %s/%s: %s: %w", goos, goarch, output, err)
				}
				if err := collect(dir, "", notices, false); err != nil {
					return err
				}
			}
		}
	}
	if len(notices) == 0 {
		return fmt.Errorf("release configuration collected no dependency notices")
	}
	// go-licenses excludes the standard library, including its vendored modules.
	for _, name := range []string{"LICENSE", "PATENTS"} {
		data, err := os.ReadFile(filepath.Join(runtime.GOROOT(), name))
		if err != nil {
			return err
		}
		notices["Go/"+name] = string(data)
	}
	if err := collect(filepath.Join(runtime.GOROOT(), "src", "vendor"), "Go/src/vendor/", notices, true); err != nil {
		return err
	}
	var output bytes.Buffer
	output.WriteString("Third-party licenses and attribution notices for Convai CLI\n\n")
	output.WriteString("Generated by make license-notices from the configured release targets,\nincluding the Go runtime and its vendored dependencies. Component licenses\nremain in effect; the CLI's Apache-2.0 license does not replace them.\n\n")
	keys := make([]string, 0, len(notices))
	for key := range notices {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	for _, key := range keys {
		fmt.Fprintf(&output, "===== %s =====\n\n%s\n\n", key, strings.TrimRight(notices[key], "\r\n"))
	}
	content := append(bytes.TrimRight(output.Bytes(), "\n"), '\n')
	const filename = "THIRD_PARTY_NOTICES.txt"
	if check {
		current, err := os.ReadFile(filename)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, content) {
			return fmt.Errorf("%s is stale; run make license-notices and review the changes", filename)
		}
		return nil
	}
	return os.WriteFile(filename, content, 0o644)
}

func collect(root, prefix string, notices map[string]string, legalOnly bool) error {
	return filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		if legalOnly && entry.Name() != "LICENSE" && entry.Name() != "NOTICE" && entry.Name() != "PATENTS" {
			return nil
		}
		if !entry.Type().IsRegular() {
			return fmt.Errorf("unexpected notice file %s", path)
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		key := prefix + filepath.ToSlash(relative)
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if len(bytes.TrimSpace(data)) == 0 {
			return fmt.Errorf("empty notice %s", key)
		}
		if old, exists := notices[key]; exists && old != string(data) {
			return fmt.Errorf("conflicting platform notices for %s", key)
		}
		notices[key] = string(data)
		return nil
	})
}
